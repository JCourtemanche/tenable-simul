def build_vulnerability_catalog(count=40):
    """Build deterministic plugin catalog. plugin_id starts at 200000."""
    catalog = []
    r = random.Random(80808)
    for idx, (cve, name, desc, cvss3, family, exploit_avail, has_patch) in enumerate(VULN_CATALOG_SEED[:count]):
        published = past_date(min_days=30, max_days=1500)
        patch_date = published + timedelta(days=r.randint(1, 30))
        modified = patch_date + timedelta(days=r.randint(1, 300))
        pid = 200000 + idx
        sev_str = severity_from_cvss(cvss3)
        sev_id = {'info': 0, 'low': 1, 'medium': 2, 'high': 3, 'critical': 4}[sev_str]
        catalog.append({
            'plugin_id': pid,
            'plugin_name': name,
            'plugin_family': family,
            'cve': cve,
            'description': desc,
            'severity': sev_id,
            'severity_str': sev_str,
            'cvss_base_score': round(min(10.0, cvss3 * 0.9), 1),
            'cvss3_base_score': cvss3,
            'cvss3_temporal_score': round(cvss3 * 0.9, 1),
            'cvss3_vector': 'CVSS:3.1/AV:N/AC:L/PR:N/UI:N/S:U/C:H/I:H/A:H',
            'vpr_score': round(min(10.0, cvss3 * 0.95), 1),
            'exploit_available': exploit_avail,
            'has_patch': has_patch,
            'patch_publication_date': iso_z(patch_date),
            'plugin_publication_date': iso_z(published),
            'plugin_modification_date': iso_z(modified),
            'vuln_publication_date': iso_z(published),
            'solution': f'Apply the vendor patch for {cve}, or the vendor-recommended workaround.',
            'synopsis': f'The remote host is affected by a vulnerability tracked as {cve}.',
            'see_also': [f'https://nvd.nist.gov/vuln/detail/{cve}'],
            'reference_information': [
                {'name': 'cve', 'value': cve, 'url': f'https://nvd.nist.gov/vuln/detail/{cve}'},
            ],
        })
    return catalog
